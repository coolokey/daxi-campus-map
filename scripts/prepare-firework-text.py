"""Build deterministic glyph particles from the official OFL Noto Sans TC font.
Usage: python scripts/prepare-firework-text.py <NotoSansTC[wght].ttf>
No browser font loading or system-font substitution is used at runtime.
"""
import sys, json, hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont
from fontTools import subset

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
labels = ['80週年', '大溪國中 生日快樂']
cmap = TTFont(source).getBestCmap()
assert all(ord(c) in cmap for c in ''.join(labels)), 'Missing Traditional Chinese glyph'
lines = []
for label, size in zip(labels, [112, 72]):
    font = ImageFont.truetype(str(source), size)
    font.set_variation_by_axes([600])
    box = font.getbbox(label)
    image = Image.new('L', (box[2]-box[0]+8, box[3]-box[1]+8))
    ImageDraw.Draw(image).text((4-box[0], 4-box[1]), label, font=font, fill=255)
    points = [[x-image.width/2, y] for y in range(0,image.height,2) for x in range(0,image.width,2) if image.getpixel((x,y)) > 110]
    lines.append(dict(label=label, width=image.width, height=image.height, points=points))
    image.save(root/f'public/campus-explorer/assets/fonts/firework-line-{len(lines)}.png')
data = dict(source='Noto Sans TC, Google Fonts, OFL-1.1', sourceSHA256=hashlib.sha256(source.read_bytes()).hexdigest(), lines=lines)
(root/'public/campus-explorer/firework-text-targets.js').write_text('/* Generated by scripts/prepare-firework-text.py; OFL license in assets/fonts. */\nwindow.CampusFireworkText = Object.freeze('+json.dumps(data, ensure_ascii=False, separators=(',',':'))+');\n', encoding='utf-8')
options=subset.Options(); options.flavor=None
font=TTFont(source); builder=subset.Subsetter(options=options); builder.populate(text=''.join(labels)); builder.subset(font)
font.save(root/'public/campus-explorer/assets/fonts/anniversary-tc.ttf')
print([(l['label'],len(l['points'])) for l in lines])
